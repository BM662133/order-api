-- Append-only audit of status changes, written in the same transaction as the change.
-- partner_id duplicates the order's so history can be read with a partner-scoped query, without a join.
CREATE TABLE order_status_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id     UUID                     NOT NULL,
    partner_id   VARCHAR(64)              NOT NULL,
    from_status  VARCHAR(16),
    to_status    VARCHAR(16)              NOT NULL,
    reason       VARCHAR(64),
    triggered_by VARCHAR(16)              NOT NULL,
    occurred_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_order_status_history_order FOREIGN KEY (order_id) REFERENCES orders (id),
    CONSTRAINT ck_order_status_history_from
        CHECK (from_status IN ('CREATED', 'VALIDATED', 'PROVISIONING', 'ACTIVE', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_order_status_history_to
        CHECK (to_status IN ('CREATED', 'VALIDATED', 'PROVISIONING', 'ACTIVE', 'FAILED', 'CANCELLED')),
    CONSTRAINT ck_order_status_history_triggered_by CHECK (triggered_by IN ('CLIENT', 'SYSTEM'))
);

-- One order's timeline in insertion order (id breaks ties between equal timestamps).
CREATE INDEX ix_order_status_history_order ON order_status_history (order_id, id);

-- Orders that predate this table get a single entry for their current status.
INSERT INTO order_status_history (order_id, partner_id, from_status, to_status, reason, triggered_by, occurred_at)
SELECT id, partner_id, NULL, status, failure_reason, 'SYSTEM', updated_at
FROM orders;
