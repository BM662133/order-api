-- Idempotency keys move to their own table so they can expire: a key is unique per partner only while
-- its row exists, and an expired row is deleted when the key is reused (or by the hourly purge).
-- orders.idempotency_key stays as the record of which key created the order.
CREATE TABLE idempotency_keys (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    partner_id      VARCHAR(64)              NOT NULL,
    idempotency_key VARCHAR(100)             NOT NULL,
    order_id        UUID                     NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    expires_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    CONSTRAINT uq_idempotency_keys_partner_key UNIQUE (partner_id, idempotency_key),
    CONSTRAINT fk_idempotency_keys_order FOREIGN KEY (order_id) REFERENCES orders (id)
);

-- Serves the purge.
CREATE INDEX ix_idempotency_keys_expires ON idempotency_keys (expires_at);

-- Existing orders keep their keys for the default 24h from creation.
INSERT INTO idempotency_keys (partner_id, idempotency_key, order_id, created_at, expires_at)
SELECT partner_id, idempotency_key, id, created_at, DATEADD('HOUR', 24, created_at)
FROM orders;

ALTER TABLE orders DROP CONSTRAINT uq_orders_partner_idempotency;
